'use strict';
// Each run rewrites last-run.json and only the marked table inside RESULTS.md, so the
// written findings there survive a rerun.
const fs = require('node:fs');
const path = require('node:path');

const E2E_ROOT = path.join(__dirname, '..', '..');
const RESULTS_PATH = path.join(E2E_ROOT, 'RESULTS.md');
const JSON_PATH = path.join(__dirname, '..', 'last-run.json');

const START_MARKER = '<!-- check-table:start (generated by sql-proof/run.cjs) -->';
const END_MARKER = '<!-- check-table:end -->';

const MAX_DETAIL_LENGTH = 600;

const escapeCell = (text) => {
  const value = String(text);
  const shortened =
    value.length > MAX_DETAIL_LENGTH ? `${value.slice(0, MAX_DETAIL_LENGTH)} ...` : value;

  return shortened.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, '<br>');
};

const buildTable = ({ results, summary, environment }) => {
  const rows = results.map(({ id, title, status, reason, failures }) => {
    const detail =
      status === 'NOT_RUN' ? reason : (failures ?? []).map((failure) => failure).join('\n');

    return `| ${id} | ${escapeCell(title)} | ${status.replace('_', ' ')} | ${escapeCell(detail ?? '')} |`;
  });

  return [
    `Last run ${environment.runAt}: **${summary.passed} passed, ${summary.failed} failed, ${summary.notRun} not run** in ${environment.durationSeconds} s.`,
    '',
    '| Check | What it proves | Result | Detail |',
    '|---|---|---|---|',
    ...rows,
    '',
    environment.notes.length > 0 ? `Notes: ${environment.notes.join('; ')}.` : '',
  ].join('\n');
};

const writeResults = ({ results, summary, environment }) => {
  fs.writeFileSync(JSON_PATH, JSON.stringify({ summary, environment, results }, null, 2));

  // Partial runs and what-if runs must not replace the record of the real code.
  if (process.env.PROOF_ONLY || process.env.PROOF_TRY_FIXES || !fs.existsSync(RESULTS_PATH)) return;

  const current = fs.readFileSync(RESULTS_PATH, 'utf8');
  const start = current.indexOf(START_MARKER);
  const end = current.indexOf(END_MARKER);

  if (start === -1 || end === -1) return;

  fs.writeFileSync(
    RESULTS_PATH,
    `${current.slice(0, start + START_MARKER.length)}\n${buildTable({ results, summary, environment })}\n${current.slice(end)}`,
  );
};

module.exports = { writeResults };
